import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { setTimeout as delay } from 'node:timers/promises';

test('API compilada exige sesión de dueño, acción explícita y bloquea descuentos de generación', async () => {
  let output = '';
  const child = spawn(process.execPath, ['-e', `
    const http = require('node:http'); const listen = http.Server.prototype.listen;
    http.Server.prototype.listen = function(...args) { this.once('listening', () => console.log('TEST_PORT='+this.address().port)); return listen.apply(this,args); };
    global.fetch = async () => { throw new Error('External network disabled in test'); };
    require('./dist/server.cjs');
  `], { cwd: import.meta.dirname, env: { ...process.env, NODE_ENV: 'production', PORT: '0', ADMIN_EMAIL: 'owner@example.test', ADMIN_PASSWORD: 'test-only-password', SUPABASE_URL: '', SUPABASE_SERVICE_ROLE_KEY: '', GEMINI_API_KEY: '' }, stdio: ['ignore', 'pipe', 'pipe'] });
  child.stdout.on('data', data => { output += data; }); child.stderr.on('data', data => { output += data; });
  try {
    for (let i = 0; i < 100 && !output.includes('TEST_PORT='); i++) await delay(50);
    const port = output.match(/TEST_PORT=(\d+)/)?.[1]; assert.ok(port, output);
    const base = 'http://127.0.0.1:'+port;
    const post = (path, body, headers={}) => fetch(base+path, { method: 'POST', headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(body) });
    assert.equal((await fetch(base+'/api/auth/session')).status, 401);
    assert.equal((await fetch(base+'/api/auth/session', {headers:{Cookie:'crm_sales_session=forged'}})).status, 401);
    assert.equal((await fetch(base+'/api/advertising')).status, 401);
    assert.equal((await fetch(base+'/api/advertising/shared-connections')).status, 401);
    assert.equal((await fetch(base+'/api/advertising/oauth/configuration')).status, 401);
    assert.equal((await fetch(base+'/api/advertising/google-ads/accounts')).status,401);
    assert.equal((await post('/api/advertising/oauth/youtube/complete',{state:'untrusted'})).status,401);
    assert.equal((await post('/api/advertising/oauth/youtube/start', {})).status, 401);
    assert.equal((await post('/api/advertising/shared-connections/verify', {})).status, 401);
    assert.equal((await post('/api/advertising/campaigns', {})).status, 401);
    const login = await post('/api/auth/login', { email: 'owner@example.test', password: 'test-only-password' }); assert.equal(login.status, 200); assert.ok(login.headers.get('set-cookie').includes('SameSite=Strict'));
    const cookie = login.headers.getSetCookie().find(value => value.startsWith('crm_sales_session=')).split(';')[0];
    const restored = await fetch(base+'/api/auth/session', {headers:{Cookie:cookie}});
    assert.equal(restored.status,200);
    assert.equal(restored.headers.get('cache-control'),'no-store');
    assert.equal(restored.headers.get('set-cookie'),null);
    const restoredBody=await restored.json();
    assert.equal(restoredBody.session.email,'owner@example.test');
    assert.equal(JSON.stringify(restoredBody).includes('test-only-password'),false);

    assert.equal((await post('/api/advertising/oauth/youtube/start', {}, { Cookie: cookie })).status, 403);
    assert.equal((await fetch(base+'/api/advertising/oauth/youtube/callback?state=untrusted&code=untrusted')).status, 409);
    assert.equal((await post('/api/advertising/shared-connections/verify', {}, { Cookie: cookie })).status, 403);
    const shared = await post('/api/advertising/shared-connections/verify', {}, { Cookie: cookie, 'X-CRM-Action': 'advertising' });
    assert.equal(shared.status, 200);
    assert.equal(shared.headers.get('cache-control'), 'no-store');
    const evidence = await shared.json();
    assert.equal(evidence.connections.length, 5);
    assert.equal(evidence.billingVerified, false);
    assert.equal(evidence.connections.every(row => row.writeVerified === false), true);
    assert.equal((await fetch(base+'/api/sales/interested-document')).status,401);
    assert.equal((await fetch(base+'/api/sales/catalog')).status,401);
    const valueBody={key:'ADMIN_EMAIL',adminPassword:'test-only-password'};
    assert.equal((await post('/api/sales/integration-value',valueBody)).status,401);
    assert.equal((await post('/api/sales/integration-value',valueBody,{Cookie:cookie})).status,403);
    const secretHeaders={Cookie:cookie,'X-CRM-Action':'sales'};
    assert.equal((await post('/api/sales/integration-value',{...valueBody,adminPassword:'wrong'},secretHeaders)).status,403);
    assert.equal((await post('/api/sales/integration-value',{...valueBody,key:'PATH'},secretHeaders)).status,400);
    const reveal=await post('/api/sales/integration-value',{key:'GEMINI_API_KEY',adminPassword:'test-only-password'},secretHeaders);
    assert.equal(reveal.status,200);assert.equal(reveal.headers.get('cache-control'),'no-store');assert.equal((await reveal.json()).value,'');
    assert.equal((await post('/api/advertising/campaigns', {}, { Cookie: cookie })).status, 403);
    assert.equal((await post('/api/advertising/campaigns', {}, { Cookie: cookie, 'X-CRM-Action': 'advertising' })).status, 400);
    assert.equal((await post('/api/ai/generate-marketing', { promotionOffer: '50% de descuento' })).status, 401);
    const blocked = await post('/api/ai/generate-marketing', { promotionOffer: '50% de descuento' }, { Cookie: cookie });
    assert.equal(blocked.status, 409); assert.match((await blocked.json()).error, /autorización/);
    assert.equal((await post('/api/advertising/plans', {})).status, 401);
    const planHeaders = { Cookie: cookie, 'X-CRM-Action': 'advertising' };
    const plan = {courseTitle:'Curso de prueba', totalBudgetDop:1000, dailyLimitDop:200, durationDays:7, targetCacDop:500, channels:['meta_ads']};
    assert.equal((await post('/api/advertising/plans', {...plan,totalBudgetDop:999}, planHeaders)).status,400);
    assert.equal((await post('/api/advertising/plans', {...plan,cvc:'test-only'}, planHeaders)).status,400);
    assert.equal((await post('/api/advertising/plans', plan, {Cookie:cookie})).status,403);
    const anonymousApproval = await post('/api/advertising/campaigns/00000000-0000-4000-8000-000000000001/approve', { reviewed: true, approveDiscount: true }, { 'X-CRM-Action': 'advertising' });
    assert.equal(anonymousApproval.status, 401);
  } finally { child.kill('SIGTERM'); if (child.exitCode === null) await once(child, 'exit'); }
});
